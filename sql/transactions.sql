CREATE TABLE IF NOT EXISTS transactions (
  id              BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  transaction_id  VARCHAR(255) NOT NULL,
  customer_id     BIGINT UNSIGNED NOT NULL,
  customer_name   VARCHAR(255) NOT NULL,
  customer_email  VARCHAR(255) NOT NULL,
  customer_phone  VARCHAR(50) NOT NULL,
  company_id      BIGINT UNSIGNED NOT NULL,
  company_name    VARCHAR(255) NOT NULL,
  employee_id     BIGINT UNSIGNED NULL,
  employee_name   VARCHAR(255) NULL,
  type            ENUM('earn','redeem') NOT NULL,
  redeem_points   INT NOT NULL,
  invoice_number  VARCHAR(255) NULL,
  invoice_image   VARCHAR(500) NULL,
  status          ENUM('pending','completed','cancelled','refunded') NOT NULL DEFAULT 'completed',
  date            VARCHAR(50) NULL,
  time            VARCHAR(50) NULL,
  notes           TEXT NULL,
  created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  UNIQUE KEY uq_transactions_transaction_id (transaction_id),
  KEY idx_transactions_customer_id (customer_id),
  KEY idx_transactions_company_id (company_id),
  KEY idx_transactions_employee_id (employee_id),
  CONSTRAINT fk_transactions_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE,
  CONSTRAINT fk_transactions_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
  CONSTRAINT fk_transactions_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE SET NULL,
  CONSTRAINT chk_transactions_redeem_points CHECK (redeem_points >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
